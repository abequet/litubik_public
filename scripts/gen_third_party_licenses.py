"""Regenerate THIRD_PARTY_LICENSES.md from what is actually installed.

    python scripts/gen_third_party_licenses.py              # rewrite the .md
    python scripts/gen_third_party_licenses.py --check      # exit 1 if stale
    python scripts/gen_third_party_licenses.py --notices out.txt

Reads the backend virtualenv's installed distributions and the frontend's
node_modules, so the inventory reflects the tree that ships rather than a
hand-maintained list that drifts. Uses only the standard library — no extra
dependency to audit.

Anything whose licence is copyleft or unrecognised is flagged; NOTICE explains
the ones that carry an obligation.

`--notices` writes the full licence texts of what the Windows build bundles
(the installed Python distributions, and the npm packages that can end up in
frontend/dist). MIT, BSD and friends ask for their notice to travel with every
copy, so the PyInstaller spec calls `write_notices()` at build time and ships
the result next to LICENSE and NOTICE.
"""
import argparse
import json
import sys
from importlib.metadata import distributions
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_LICENSES.md"

# Licences that constrain redistribution. Not a verdict — a prompt to check.
COPYLEFT = ("gpl", "agpl", "lgpl", "mpl", "epl", "cddl", "eupl", "osl",
            "sspl", "bsl", "cc-by-sa", "cc by-sa")
PERMISSIVE_HINTS = ("mit", "bsd", "apache", "isc", "psf", "python-2.0",
                    "unlicense", "zlib", "cc0", "0bsd", "postgresql")
LICENSE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")


def _norm(text: str) -> str:
    return " ".join((text or "").split())[:80]


def python_packages() -> list[tuple[str, str, str]]:
    rows = []
    for dist in distributions():
        meta = dist.metadata
        name = meta.get("Name") or dist.name
        if not name:
            continue
        lic = meta.get("License-Expression") or meta.get("License") or ""
        # some projects paste their whole licence text in the License field
        # (scipy): the classifier says it better
        if "\n" in lic.strip():
            lic = ""
        if not lic or lic.lower() in ("unknown", "none"):
            classifiers = [c for c in meta.get_all("Classifier") or []
                           if c.startswith("License ::")]
            lic = classifiers[-1].split("::")[-1].strip() if classifiers else ""
        rows.append((name, meta.get("Version") or "",
                     _norm(lic) or "(non déclarée)"))
    # a distribution can be seen twice through different paths
    seen, out = set(), []
    for name, ver, lic in sorted(rows, key=lambda r: r[0].lower()):
        if name.lower() in seen:
            continue
        seen.add(name.lower())
        out.append((name, ver, lic))
    return out


def npm_packages() -> list[tuple[str, str, str]]:
    modules = ROOT / "frontend" / "node_modules"
    if not modules.is_dir():
        return []
    rows = {}
    for pkg in modules.rglob("package.json"):
        # skip nested fixtures and non-package files
        parts = pkg.relative_to(modules).parts
        if len(parts) > 3 or parts[-1] != "package.json":
            continue
        try:
            data = json.loads(pkg.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        name, ver = data.get("name"), data.get("version")
        if not name or not ver:
            continue
        lic = data.get("license")
        if isinstance(lic, dict):
            lic = lic.get("type", "")
        if not lic and isinstance(data.get("licenses"), list):
            lic = "/".join(x.get("type", "") for x in data["licenses"])
        rows[name] = (name, ver, _norm(lic) or "(non déclarée)")
    return sorted(rows.values(), key=lambda r: r[0].lower())


def flag(lic: str) -> str:
    low = lic.lower()
    if any(k in low for k in COPYLEFT):
        return "⚠"
    if any(k in low for k in PERMISSIVE_HINTS):
        return ""
    return "?"


def table(rows: list[tuple[str, str, str]]) -> str:
    lines = ["| | Package | Version | Licence |", "|---|---|---|---|"]
    for name, ver, lic in rows:
        lines.append(f"| {flag(lic)} | `{name}` | {ver} | {lic} |")
    return "\n".join(lines)


def render() -> tuple[str, int, int, int]:
    py, npm = python_packages(), npm_packages()
    flagged = [(n, v, lic) for n, v, lic in py + npm if flag(lic) in ("⚠", "?")]
    body = f"""# Third-party licences

*Generated by `scripts/gen_third_party_licenses.py` — do not edit by hand.*
Re-run it after changing a dependency.

`⚠` marks a copyleft or redistribution-constraining licence, `?` one this script
could not classify. Both mean "read it", not "problem". [NOTICE](NOTICE)
explains the ones that carry an actual obligation for LitUbik — PyMuPDF above
all, whose AGPL is the reason this project cannot be relicensed permissively.
The Windows release also ships `THIRD_PARTY_NOTICES.txt`, the full licence
texts of the bundled packages.

**{len(flagged)} of {len(py) + len(npm)} packages need a look**: \
{", ".join(f"`{n}`" for n, _, _ in flagged) or "none"}.

## Python ({len(py)} distributions)

Everything installed in the backend environment, which is wider than
`requirements.txt`: transitive dependencies are included, because they ship too.

{table(py)}

## npm ({len(npm)} packages)

{table(npm)}
"""
    return body, len(py), len(npm), len(flagged)


# --- full licence texts, for the binary distribution -------------------------

def _is_licence_file(name: str) -> bool:
    return name.upper().startswith(LICENSE_NAMES)


def _python_notices() -> list[tuple[str, str]]:
    out, seen = [], set()
    for dist in sorted(distributions(),
                       key=lambda d: (d.metadata.get("Name") or "").lower()):
        name = dist.metadata.get("Name") or dist.name
        if not name or name.lower() in seen:
            continue
        seen.add(name.lower())
        texts = []
        for f in dist.files or []:
            if not _is_licence_file(Path(str(f)).name):
                continue
            try:
                texts.append(Path(dist.locate_file(f)).read_text(
                    encoding="utf-8", errors="replace").strip())
            except OSError:
                continue
        head = f"{name} {dist.metadata.get('Version') or ''}".strip()
        out.append((head, "\n\n".join(texts)))
    return out


def _npm_notices() -> list[tuple[str, str]]:
    """Packages that can end up in frontend/dist: the lockfile entries not
    marked dev (direct and transitive runtime dependencies)."""
    front = ROOT / "frontend"
    lock = front / "package-lock.json"
    if not lock.is_file():
        return []
    packages = json.loads(lock.read_text(encoding="utf-8")).get("packages", {})
    out = []
    for key, info in sorted(packages.items()):
        if not key or info.get("dev") or info.get("devOptional"):
            continue
        folder = front / key
        if not folder.is_dir():
            continue  # an optional platform build not installed here
        texts = [p.read_text(encoding="utf-8", errors="replace").strip()
                 for p in sorted(folder.iterdir())
                 if p.is_file() and _is_licence_file(p.name)]
        name = key.split("node_modules/")[-1]
        out.append((f"{name} {info.get('version', '')}".strip(),
                    "\n\n".join(texts)))
    return out


def write_notices(path: Path) -> int:
    """Full licence texts of the bundled third-party code, one block each."""
    rule = "=" * 78
    blocks = ["Third-party notices for the LitUbik Windows build",
              "",
              "Generated by scripts/gen_third_party_licenses.py at build time.",
              "THIRD_PARTY_LICENSES.md lists the licence of each package; this",
              "file carries the notice texts those licences ask to be",
              "distributed with every copy.",
              ""]
    n = 0
    for section, rows in (("Python distributions", _python_notices()),
                          ("npm packages bundled in the web interface",
                           _npm_notices())):
        blocks += ["#" * 78, f"# {section}", "#" * 78, ""]
        for head, text in rows:
            n += 1
            blocks += [rule, head, rule,
                       text or "(no licence file shipped with the package; "
                               "see THIRD_PARTY_LICENSES.md)", ""]
    Path(path).write_text("\n".join(blocks), encoding="utf-8")
    return n


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if THIRD_PARTY_LICENSES.md is out of date")
    ap.add_argument("--notices", metavar="PATH",
                    help="write the full licence texts to PATH and stop")
    args = ap.parse_args()

    if args.notices:
        n = write_notices(Path(args.notices))
        print(f"{args.notices}: notices for {n} packages")
        return 0

    body, n_py, n_npm, n_flag = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != body:
            print(f"{OUT.name} is out of date: run "
                  "scripts/gen_third_party_licenses.py and commit the result")
            return 1
        print(f"{OUT.name} is up to date")
        return 0
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {n_py} Python + {n_npm} npm, "
          f"{n_flag} flagged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
